def normalized(value):
    return str(value or "").strip().casefold()


def remove_artificial_hint(french):
    return re.sub(
        r"\s*\(indice anglais\s*:\s*«.*?…\s*»,\s*\d+\s+lettres\)\s*$",
        "",
        str(french or ""),
    ).strip()


def progression_score(word):
    return (
        int(word.get("level") or 0),
        int(word.get("successCount") or 0),
        int(word.get("responseCount") or 0),
        1 if word.get("isFailed") is False else 0,
        str(word.get("nextReview") or ""),
    )


def merge_duplicate(kept, candidate):
    best = max((kept, candidate), key=progression_score)
    merged = dict(best)
    for key in set(kept) | set(candidate):
        if key not in merged or merged[key] in (None, ""):
            merged[key] = kept.get(key, candidate.get(key))
    for key in ("successCount", "failCount", "responseCount", "totalResponseTime"):
        if key in kept or key in candidate:
            merged[key] = max(int(kept.get(key) or 0), int(candidate.get(key) or 0))
    return merged


def main():
    with DATA_FILE.open(encoding="utf-8") as stream:
        data = json.load(stream)

    words = data["mots"]
    backup = DATA_FILE.with_name(
        f"luc_vocab.backup-{datetime.now().strftime('%Y%m%d-%H%M%S')}.json"
    )
    shutil.copy2(DATA_FILE, backup)

    hints_removed = 0
    for word in words:
        clean_french = remove_artificial_hint(word.get("fr"))
        if clean_french != word.get("fr"):
            word["fr"] = clean_french
            hints_removed += 1

    changed = 0
    for word in words:
        key = (normalized(word.get("fr")), normalized(word.get("en")))
        context = CONTEXTS.get(key)
        if context and f"({context})" not in str(word["fr"]):
            word["fr"] = f"{str(word['fr']).strip()} ({context})"
            word.pop("guide", None)
            changed += 1

    unique = []
    positions = {}
    duplicates = 0
    for word in words:
        key = (normalized(word.get("en")), normalized(word.get("fr")))
        if key not in positions:
            positions[key] = len(unique)
            unique.append(word)
        else:
            index = positions[key]
            unique[index] = merge_duplicate(unique[index], word)
            duplicates += 1

    data["mots"] = unique
    with DATA_FILE.open("w", encoding="utf-8", newline="\n") as stream:
        json.dump(data, stream, ensure_ascii=False, indent=2)
        stream.write("\n")

    groups = defaultdict(set)
    for word in unique:
        groups[normalized(word.get("fr"))].add(normalized(word.get("en")))
    remaining = sum(1 for values in groups.values() if len(values) > 1)

    print(f"Backup: {backup}")
    print(f"Artificial hints removed: {hints_removed}")
    print(f"Contexts added: {changed}")
    print(f"Exact duplicates merged: {duplicates}")
    print(f"Entries: {len(words)} -> {len(unique)}")
    print(f"Shared French labels remaining: {remaining}")


if __name__ == "__main__":
    main()
